import re
import sys
from datetime import date, time
from pathlib import Path

import numpy as np
import pandas as pd
import plotly.graph_objects as go
import streamlit as st
import torch
import torch.nn.functional as F

HERE = Path(__file__).resolve().parent
ROOT = next(p for p in [HERE, *HERE.parents] if (p / "data" / "tokenizer.py").exists())
sys.path[:0] = [str(ROOT / "data"), str(HERE)]
from tokenizer import GridTokenizer
from GPT1_0 import GPT

DATA_DIR = ROOT / "data" / "raw"
device = "cuda" if torch.cuda.is_available() else "cpu"


# ---------------- loading (cached: done once, not on every click) ----------------
@st.cache_resource
def load_model(path):
    ckpt = torch.load(path, map_location=device)
    s = ckpt["settings"]
    run_name = re.split(r"[\\/]", ckpt["tokenizer_run"].rstrip("\\/"))[-1]   # works for Win + Linux paths
    tok = GridTokenizer.load(ROOT / "data" / "tokenizer_runs" / run_name / "tokenizer.json")
    model = GPT(tok.vocab_size, s["embed_dim"], s["context"], s["n_heads"], s["n_layers"]).to(device)
    model.load_state_dict(ckpt["model"])
    model.eval()
    return model, tok, s, ckpt


@st.cache_data
def load_candles(symbol, interval):
    return pd.read_parquet(DATA_DIR / f"{symbol}_{interval}.parquet")


# ---------------- tokens -> candles ----------------
def sigma_of(returns, W):
    return np.std(returns[-W:], ddof=1)                           # same sigma as the tokenizer


def decode_features(tok, tokens):
    dec = tok.decode(np.asarray(tokens).ravel())
    shape = np.shape(tokens)
    return {f: (dec[f].to_numpy().reshape(shape) if f in dec else np.zeros(shape))
            for f in ("ret", "upper", "lower", "relvol")}


def free_run_candles(tok, tokens, past_ret, past_vol, last_close):
    """tokens (P, N) generated by the model -> OHLCV (P, N, 5), each path built on itself."""
    W, (P, N) = tok.window, tokens.shape
    f = decode_features(tok, tokens)
    out = np.zeros((P, N, 5))
    for p in range(P):
        rets, vols, close = list(past_ret), list(past_vol), last_close
        for n in range(N):
            sigma = sigma_of(rets, W)
            o, c = close, close * np.exp(f["ret"][p, n] * sigma)
            h = max(o, c) * np.exp(f["upper"][p, n] * sigma)
            lo = min(o, c) * np.exp(-f["lower"][p, n] * sigma)
            v = np.mean(vols[-W:]) * np.exp(f["relvol"][p, n])
            out[p, n] = (o, h, lo, c, v)
            rets.append(np.log(c / o))
            vols.append(v)
            close = c
    return out


# ---------------- the two prediction modes ----------------
@torch.no_grad()
def predict_free_run(model, T, context, n_future, n_paths, temperature):
    x = torch.tensor(context, device=device).repeat(n_paths, 1)
    first = None
    for n in range(n_future):
        probs = F.softmax(model(x[:, -T:])[:, -1, :] / temperature, dim=-1)
        if n == 0:
            first = probs[0].cpu().numpy()
        x = torch.cat([x, torch.multinomial(probs, 1)], dim=1)
    return x[:, T:].cpu().numpy(), first


@torch.no_grad()
def predict_one_step(model, T, tokens, k, n_future, temperature):
    """Distribution for candle k+n given the REAL tokens before it, for n = 0..N-1."""
    windows = np.stack([tokens[k + n - T: k + n] for n in range(n_future)])
    logits = model(torch.tensor(windows, device=device))[:, -1, :] / temperature
    return F.softmax(logits, dim=-1).cpu().numpy()              # (N, V)


# ---------------- page ----------------
st.set_page_config(page_title="Candle GPT predictions", layout="wide")
st.title("Candle GPT predictions")

runs = sorted(ROOT.glob("**/runs/gpt_*.pt"))
if not runs:
    st.error("No trained models found (looking for runs/gpt_*.pt).")
    st.stop()

with st.sidebar:
    run = st.selectbox("Model", runs, index=len(runs) - 1, format_func=lambda p: p.name)
    interval = st.text_input("Interval of the data", "1m")
    symbols = sorted(p.name.rsplit("_", 1)[0] for p in DATA_DIR.glob(f"*_{interval}.parquet"))
    symbol = st.selectbox("Coin", symbols, index=symbols.index("BTCUSDT") if "BTCUSDT" in symbols else 0)
    day = st.date_input("Start date (UTC)", date(2026, 8, 10))
    clock = st.time_input("Start time (UTC)", time(14, 0), step=60)
    mode = st.radio("Mode", ["Free run: model continues on its own predictions",
                             "One step ahead: always real history"])
    n_future = st.slider("Candles to predict", 5, 240, 30)
    n_paths = st.slider("Sampled paths", 10, 500, 100, step=10)
    temperature = st.slider("Temperature", 0.3, 2.0, 1.0, step=0.1)
    show_history = st.slider("Real candles shown before start", 10, 300, 60)
    seed = st.number_input("Seed", value=0, step=1)
    go_button = st.button("Predict", type="primary")

model, tok, s, ckpt = load_model(str(run))
T, W = s["context"], tok.window
st.caption(f"{run.name}: val {ckpt['val_bits']:.3f} bits/token "
           f"(unigram {ckpt.get('unigram_bits', float('nan')):.3f}) | context {T} candles | {device}")

if not go_button:
    st.info("Choose settings in the sidebar and press Predict.")
    st.stop()

torch.manual_seed(int(seed))
df = load_candles(symbol, interval)
start = pd.Timestamp.combine(day, clock).tz_localize("UTC")
i = df.index.searchsorted(start)
lead = T + W + 10
if i < lead or i >= len(df):
    st.error("Not enough data around this start time.")
    st.stop()

seg = df.iloc[i - lead: i + n_future]                           # history + real future
tokens = tok.encode(seg).to_numpy()
closes = seg["close"].to_numpy()
log_ret = np.diff(np.log(closes))                               # log_ret[j-1] = return of candle j
k = lead                                                        # index of the first predicted candle
n_real = len(seg) - k                                           # real future candles available
if (tokens[k - T: k] < 0).any():
    st.error("The context before this start time contains missing data. Pick another time.")
    st.stop()

step = pd.Timedelta(interval.replace("m", "min"))
times = start + step * np.arange(n_future)
shown = df.iloc[i - show_history: i + n_future]                 # real candles to draw
fig = go.Figure(go.Candlestick(x=shown.index, open=shown["open"], high=shown["high"],
                               low=shown["low"], close=shown["close"], name="real"))

if mode.startswith("Free"):
    gen, first = predict_free_run(model, T, tokens[k - T: k], n_future, n_paths, temperature)
    paths = free_run_candles(tok, gen, log_ret[k - 1 - W: k - 1],
                             seg["volume"].to_numpy()[k - W: k], closes[k - 1])
    q10, q50, q90 = np.percentile(paths[:, :, 3], [10, 50, 90], axis=0)
    ex = paths[0]
    fig.add_trace(go.Candlestick(x=times, open=ex[:, 0], high=ex[:, 1], low=ex[:, 2],
                                 close=ex[:, 3], name="one sampled path", opacity=0.6,
                                 increasing_line_color="#7e57c2", decreasing_line_color="#7e57c2"))
else:
    if n_real < n_future or (tokens[k: k + n_future] < 0).any():
        st.error("One step ahead needs real data (without gaps) for the whole horizon.")
        st.stop()
    probs = predict_one_step(model, T, tokens, k, n_future, temperature)    # (N, V)
    first = probs[0]
    ret_value = decode_features(tok, np.arange(tok.vocab_size))["ret"]       # ret of every token
    q10, q50, q90 = (np.zeros(n_future) for _ in range(3))
    rng = np.random.default_rng(int(seed))
    for n in range(n_future):
        m = k + n                                               # candle being predicted
        sigma = sigma_of(log_ret[: m - 1], W)                   # from the real returns before it
        draws = rng.choice(tok.vocab_size, size=n_paths, p=probs[n] / probs[n].sum())
        pred_close = closes[m - 1] * np.exp(ret_value[draws] * sigma)
        q10[n], q50[n], q90[n] = np.percentile(pred_close, [10, 50, 90])
    actual_p = probs[np.arange(n_future), tokens[k: k + n_future]]
    bits = -np.log2(np.maximum(actual_p, 1e-12))
    c1, c2, c3 = st.columns(3)
    c1.metric("Bits on these real candles", f"{bits.mean():.3f}")
    c2.metric("Model's validation average", f"{ckpt['val_bits']:.3f}")
    c3.metric("Most surprising candle", f"{bits.max():.1f} bits")

fig.add_trace(go.Scatter(x=times, y=q90, line=dict(width=0), showlegend=False, hoverinfo="skip"))
fig.add_trace(go.Scatter(x=times, y=q10, fill="tonexty", fillcolor="rgba(66,165,245,0.25)",
                         line=dict(width=0), name="10-90 % range"))
fig.add_trace(go.Scatter(x=times, y=q50, line=dict(color="#1565c0", width=2), name="median"))
fig.add_vline(x=times[0], line=dict(color="gray", dash="dash"))
fig.update_layout(height=600, xaxis_rangeslider_visible=False, margin=dict(t=30),
                  title=f"{symbol} {interval} from {start:%Y-%m-%d %H:%M} UTC")
st.plotly_chart(fig, use_container_width=True)

st.subheader("Model's top 5 guesses for the first candle")
top = np.argsort(-first)[:5]
table = tok.decode(top)
table.insert(0, "probability", first[top].round(4))
table.insert(0, "token", top)
st.dataframe(table, hide_index=True)
if n_real > 0 and tokens[k] >= 0:
    st.write(f"Actual first token: **{tokens[k]}**, model probability {first[tokens[k]]:.2e}, "
             + ", ".join(f"{f} {v:+.2g}" for f, v in tok.decode([tokens[k]]).iloc[0].items()))